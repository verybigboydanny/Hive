"""Render the tool reference for docs/backend-contract.md from the registry (single source of truth)."""

from __future__ import annotations

from .catalog import ALL_TOOLS

BEGIN, END = "<!-- BEGIN TOOLS (generated by `hive gen-contract`; do not edit) -->", "<!-- END TOOLS -->"
GROUP_TITLES = {"agents": "Agents", "files": "Filesystem", "tasks": "Tasks", "messages": "Messaging",
                "handoffs": "Handoffs", "memory": "Memory and decisions", "project": "Project, activity and checkpoints", "terminal": "Terminal and execution"}


def _type(p: dict) -> str:
    t = p.get("type", "any")
    t = "/".join(t) if isinstance(t, list) else t
    if p.get("enum"):
        t += " (" + " \\| ".join(map(str, p["enum"])) + ")"
    if p.get("type") == "array" and "items" in p:
        inner = p["items"].get("type", "any")
        t = f"array of {inner}"
    return t


def _shape(schema: dict) -> str:
    parts = []
    for k, v in schema.get("properties", {}).items():
        parts.append(f"`{k}`: {_type(v)}")
    return ", ".join(parts)


def render_tools_markdown() -> str:
    out = [BEGIN, ""]
    for group, title in GROUP_TITLES.items():
        specs = [s for s in ALL_TOOLS if s.group == group]
        if not specs:
            continue
        out += [f"### {title}", ""]
        for s in specs:
            flags = [f for f, on in (("read-only", s.read_only), ("destructive", s.destructive),
                                     ("idempotent", s.idempotent), ("needs registered agent", s.requires_agent)) if on]
            out += [f"#### `{s.name}`", "", s.description, "", f"*{', '.join(flags) or 'no flags'}*", ""]
            props, req = s.input_schema["properties"], set(s.input_schema["required"])
            if props:
                out += ["| Parameter | Type | Required | Description |", "|---|---|---|---|"]
                for name, p in props.items():
                    desc = p.get("description", "").replace("|", "\\|")
                    lim = [f"max {p['maxLength']} chars" if "maxLength" in p else "",
                           f"min {p['minimum']}" if "minimum" in p else "", f"max {p['maximum']}" if "maximum" in p else ""]
                    lim = ", ".join(x for x in lim if x)
                    out.append(f"| `{name}` | {_type(p)} | {'yes' if name in req else 'no'} | {desc}{' (' + lim + ')' if lim else ''} |")
            else:
                out.append("No parameters.")
            out += ["", f"**Returns** (`data`): {_shape(s.output_schema)}", ""]
    out.append(END)
    return "\n".join(out) + "\n"


def splice(doc: str, rendered: str) -> str:
    if BEGIN not in doc or END not in doc:
        raise ValueError("document has no generated-tools markers")
    head = doc[:doc.index(BEGIN)]
    tail = doc[doc.index(END) + len(END):]
    return head + rendered.rstrip("\n") + tail
